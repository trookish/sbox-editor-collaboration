param([string]$SboxRoot='C:\Program Files (x86)\Steam\steamapps\common\sbox',[switch]$Stop)
$ErrorActionPreference='Stop'
$stopRoot=Join-Path ([IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))) '.collaboration/test-copies'
if($Stop) {
    # Closes only the editors this script started, by the process ids it recorded; an editor the person opened is never touched.
    foreach($copyName in @('A','B')) {
        $pidFile=Join-Path $stopRoot "$copyName/.collaboration/editor.pid"
        if(!(Test-Path -LiteralPath $pidFile)) {continue}
        $id=[int](Get-Content -LiteralPath $pidFile -Raw).Trim()
        $process=Get-Process -Id $id -ErrorAction SilentlyContinue
        if($process -and $process.ProcessName -eq 'sbox-dev') { Stop-Process -Id $id -Force; Write-Host "Closed editor $copyName (PID $id)" }
        Remove-Item -LiteralPath $pidFile -Force
    }
    return
}
# Windows PowerShell 5.1 has no [IO.Path]::GetRelativePath (added in .NET Core 2.1).
# This shim keeps the fixture copy working on the 5.1 runtime that ships with Windows.
if(-not ('CollabPath' -as [type])) {
Add-Type -TypeDefinition @'
using System;
public static class CollabPath {
    public static string Relative(string basePath, string fullPath) {
        var baseUri = new Uri(TrimEnd(basePath) + System.IO.Path.DirectorySeparatorChar);
        var targetUri = new Uri(fullPath);
        var rel = Uri.UnescapeDataString(baseUri.MakeRelativeUri(targetUri).ToString());
        return rel.Replace('/', System.IO.Path.DirectorySeparatorChar);
    }
    static string TrimEnd(string p) { return p.TrimEnd(System.IO.Path.DirectorySeparatorChar, System.IO.Path.AltDirectorySeparatorChar); }
}
'@
}
$workspace=[IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$testRoot=Join-Path $workspace '.collaboration/test-copies'
$openEditors=Get-CimInstance Win32_Process -Filter "Name = 'sbox-dev.exe'"
if($openEditors) {
    $details=($openEditors | ForEach-Object { "PID $($_.ProcessId): $($_.CommandLine)" }) -join [Environment]::NewLine
    throw "Close every open s&box editor before preparing the two-process fixtures. This s&box build redirects a new launch while another editor is open.$([Environment]::NewLine)$details"
}
# Only disposable fixtures are overwritten. No test runs against the user's original scene.
foreach($copyName in @('A','B')) {
    $copyRoot=Join-Path $testRoot $copyName
    New-Item -ItemType Directory -Force $copyRoot | Out-Null
    foreach($folder in @('Assets','Code','Libraries','ProjectSettings')) {
        $source=Join-Path $workspace $folder
        foreach($file in Get-ChildItem -LiteralPath $source -File -Recurse) {
            $relative=CollabPath::Relative($workspace,$file.FullName)
            if($relative -match '[\\/](obj|bin|Properties|\.sbox)[\\/]|\.csproj$|_c$|_d$|\.generated\.') {continue}
            $destination=Join-Path $copyRoot $relative
            New-Item -ItemType Directory -Force ([IO.Path]::GetDirectoryName($destination)) | Out-Null
            Copy-Item -LiteralPath $file.FullName -Destination $destination -Force
        }
    }
    Copy-Item -LiteralPath (Join-Path $workspace 'Collab_Library_Testing.sbproj') -Destination $copyRoot -Force
    foreach($subdir in @('Editor','.collaboration')) { New-Item -ItemType Directory -Force (Join-Path $copyRoot $subdir) | Out-Null }
    # Marks the folder as a disposable copy (TestHarnessRules.MarkerFile), which the session checks before it treats the copy as a test fixture.
    Set-Content -LiteralPath (Join-Path $copyRoot '.collaboration/disposable-test-copy.txt') -Value 'Disposable two-editor test copy made by Tools/Prepare-EditorTests.ps1. Safe to delete.'
    Copy-Item -LiteralPath (Join-Path $PSScriptRoot 'EditorProbe.cs') -Destination (Join-Path $copyRoot 'Editor/EditorProbe.cs') -Force
    Copy-Item -LiteralPath (Join-Path $workspace 'Assets/scenes/minimal.scene') -Destination (Join-Path $copyRoot 'Assets/scenes/secondary.scene') -Force
}
# Start sequentially: s&box currently writes a shared config/addons.json on startup.
foreach($copyName in @('A','B')) {
    $copyRoot=Join-Path $testRoot $copyName
    if($copyName -eq 'B') {
        # Preserve asset metadata generated by A; independently generated metadata is intentionally incompatible.
        Copy-Item -LiteralPath (Join-Path $testRoot 'A/Assets/scenes/secondary.scene.meta') -Destination (Join-Path $copyRoot 'Assets/scenes/secondary.scene.meta') -Force
    }
    $process=Start-Process -FilePath (Join-Path $SboxRoot 'sbox-dev.exe') -ArgumentList @('-project',('"'+(Join-Path $copyRoot 'Collab_Library_Testing.sbproj')+'"'),'-novid') -WindowStyle Hidden -PassThru
    $process.Id | Set-Content (Join-Path $copyRoot '.collaboration/editor.pid')
    $ready=$false
    for($attempt=0;$attempt -lt 6;$attempt++) {
        try { $reply=& "$PSScriptRoot/Invoke-Probe.ps1" -Copy $copyName -Command status | ConvertFrom-Json; if($reply.success){$ready=$true;break} } catch { Write-Host "Waiting for editor $copyName startup…" }
    }
    if(!$ready){throw "Editor $copyName failed to start. Inspect s&box/logs and the copy's compile errors."}
    Write-Host "Editor $copyName ready (PID $($process.Id))"
}
