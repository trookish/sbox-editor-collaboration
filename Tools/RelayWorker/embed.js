// Copies the relay Worker's source into the library as a C# string, so the editor can deploy the relay for a person who installed only the library
// (they do not have this Tools folder). Run it after every change to src/index.js; the library's test suite fails when the two differ.
//
//     npm run embed

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = readFileSync(resolve(here, "src/index.js"), "utf8").replace(/\r\n/g, "\n").replace(/\n+$/, "");
const target = resolve(here, "../../Libraries/collaboration/Editor/Core/RelayWorkerSource.cs");

// A C# raw string needs a delimiter longer than any run of quotes inside it.
let longest = 0;
for (const run of source.match(/"+/g) ?? []) {
	longest = Math.max(longest, run.length);
}
const fence = '"'.repeat(Math.max(3, longest + 1));

const file = `namespace TeamCreate;

/// <summary>
/// The relay Worker, exactly as it is in Tools/RelayWorker/src/index.js. The editor uploads this text to the person's own Cloudflare account when they
/// press Set up relay. Generated by \`npm run embed\` in Tools/RelayWorker; do not edit by hand. The test suite compares it with the file and fails on a difference.
/// </summary>
public static class RelayWorkerSource
{
    public const string Text = ${fence}
${source}
${fence};
}
`;

writeFileSync(target, file, "utf8");
console.log("Wrote " + target + " (" + source.length + " characters of Worker source).");
